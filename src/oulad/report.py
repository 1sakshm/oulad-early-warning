"""Tables and figures from results/summary.json. Usage: python -m oulad.report (from src/)."""
import json
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

OUT = Path(__file__).resolve().parents[2] / "results"
NAMES = {"logistic": "Logistic regression", "boosted": "Gradient-boosted trees",
         "gru": "GRU sequence model", "boosted_protected": "Boosted + demographics", "majority": "Majority class"}
ATTRS = {"gender": "Gender", "age_band": "Age band", "imd_quintile": "Deprivation (IMD)", "disability": "Disability"}


def fmt_ci(v):
    return f"[{v[0]:.3f}, {v[1]:.3f}]"


def tables(s):
    lines = ["# Results", "", "Generated by `python -m oulad.report` from `summary.json`.", ""]
    for day in ("day14", "day28"):
        d = s[day]
        lines += [f"## Cutoff {day[3:]} days", "",
                  f"Later run: {d['n_train']} training enrolments (2013), {d['n_test']} test enrolments (2014, "
                  f"unseen students), pass rate {d['pass_rate_test']:.1%}.", "",
                  "| Model | Later-run AUROC [95 % CI] | Random-split AUROC, mean (range) | Drop [95 % CI] | p (H1) |",
                  "|---|---|---|---|---|"]
        for m, name in NAMES.items():
            lr, rs = d["later_run"][m], d["random_split"][m]
            dr = d["transfer_drop"].get(m)
            drop = f"{dr['drop']:+.3f} {fmt_ci(dr['ci'])}" if dr else "–"
            p = f"{dr['p_one_sided']:.3f}" if dr else "–"
            lines.append(f"| {name} | {lr['auc']:.3f} {fmt_ci(lr['auc_ci'])} | {rs['auc_mean']:.3f} "
                         f"({rs['auc_range'][0]:.3f}–{rs['auc_range'][1]:.3f}) | {drop} | {p} |")
        lines += ["", "Group gaps on the later run (largest difference between levels; levels under 200 test "
                  "students are listed but left out of the gap):", "",
                  "| Model | Attribute | AUROC gap [95 % CI] | Missed at-risk (FNR) gap [95 % CI] | Levels: n, AUROC, FNR |",
                  "|---|---|---|---|---|"]
        for m in ("boosted", "logistic", "gru"):
            for a, name in ATTRS.items():
                f = d["fairness"][m][a]
                lv = "; ".join(f"{k}: {v['n']}, {v['auc']:.3f}, {v['fnr']:.2f}" for k, v in f["levels"].items())
                lines.append(f"| {NAMES[m]} | {name} | {f['auc_gap']:.3f} {fmt_ci(f['auc_gap_ci'])} | "
                             f"{f['fnr_gap']:.3f} {fmt_ci(f['fnr_gap_ci'])} | {lv} |")
        lines.append("")
    h = s["h2_day28_minus_day14"]
    lines += ["## H2: day 28 vs day 14 (gradient-boosted trees, same test enrolments)", "",
              f"AUROC difference {h['diff']:+.3f} {fmt_ci(h['ci'])}, one-sided p = {h['p_one_sided']:.3f}, "
              f"n = {h['n']}.", ""]
    (OUT / "RESULTS.md").write_text("\n".join(lines), encoding="utf8")


def figures(s):
    models = ["logistic", "boosted", "gru", "boosted_protected"]
    fig, axes = plt.subplots(1, 2, figsize=(10, 3.8), sharey=True)
    for ax, day in zip(axes, ("day14", "day28")):
        d = s[day]
        x = range(len(models))
        later = [d["later_run"][m]["auc"] for m in models]
        err = [[l - d["later_run"][m]["auc_ci"][0] for l, m in zip(later, models)],
               [d["later_run"][m]["auc_ci"][1] - l for l, m in zip(later, models)]]
        rand = [d["random_split"][m]["auc_mean"] for m in models]
        ax.bar([i - 0.2 for i in x], rand, 0.4, label="Random split (mean of 5)", color="#9aa5b1")
        ax.bar([i + 0.2 for i in x], later, 0.4, yerr=err, capsize=3, label="Later run (95 % CI)", color="#2f6f9f")
        ax.set_xticks(list(x), [NAMES[m].replace(" + ", "\n+ ").replace("Gradient-boosted", "Boosted")
                                for m in models], fontsize=8)
        ax.set_title(f"First {day[3:]} days")
        ax.set_ylim(0.5, max(rand + later) + 0.05)
    axes[0].set_ylabel("AUROC (pass vs at risk)")
    axes[0].legend(fontsize=8, loc="upper left")
    fig.tight_layout()
    fig.savefig(OUT / "auroc_by_split.png", dpi=200)

    fig, axes = plt.subplots(1, 4, figsize=(12, 3.4), sharey=True)
    f = s["day14"]["fairness"]["boosted"]
    for ax, (a, name) in zip(axes, ATTRS.items()):
        lv = f[a]["levels"]
        ks = list(lv)
        ax.bar(range(len(ks)), [lv[k]["auc"] for k in ks], color="#2f6f9f")
        ax.set_xticks(range(len(ks)), ks, rotation=45, ha="right", fontsize=8)
        ax.set_title(name, fontsize=10)
        ax.set_ylim(0.5, 0.85)
    axes[0].set_ylabel("Later-run AUROC, day 14")
    fig.tight_layout()
    fig.savefig(OUT / "auroc_by_group_day14.png", dpi=200)


if __name__ == "__main__":
    summary = json.loads((OUT / "summary.json").read_text())
    tables(summary)
    figures(summary)
    print("wrote RESULTS.md and figures")
